export function getLocalizedCountries(languageCode: string): { code: string; name: string }[] {
  return countries.map(country => ({
    code: country.code,
    name: getCountryName(country, languageCode)
  }));
}

export function getCountryName(country: Country, languageCode: string): string {
  switch (languageCode) {
    case 'zh':
      return country.nameZh;
    case 'en':
      return country.nameEn;
    case 'jp':
    default:
      return country.nameJa;
  }
}
